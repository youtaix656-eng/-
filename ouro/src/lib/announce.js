// 「終わったことを知らせる」文。
//
// **`resume.js` から切り出してあるのは起動を軽くするため。** 起動時に要るのは
// この1行だけで、再開の仕組み本体（中断された仕事を探して走らせ直す）は
// 開いた時にしか要らない。`resume.js` からも再輸出しているので、
// これまでの読み込み方は変わらない。

/** 知らせの文言。1件と複数で言い方を変える（「1件の成果物」は不自然）。 */
export function doneMessage(tasks = []) {
  if (!tasks.length) return '';
  if (tasks.length === 1) return '成果物が完成しました！';
  return `成果物が${tasks.length}件 完成しました！`;
}
