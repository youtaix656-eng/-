// キャラクターの一言。**JSX から切り出してある**のは、
// 実際に画面へ出る文字列をテストから直接読めるようにするため
// （「責めていないこと」をコメントの文言ではなく、出る文で確かめたい）。
//
// 決めていること（README 決まり9）
//  - 調子を評価しない（「よくない状態です」と言わない）。
//  - 記録しなかったことを責めない・急かさない。
//  - 「がんばって」で終わらせない——つらい日にできることは、もう終わっている。

export const GUT_LINES = {
  none: 'きょうはどうですか。ひとつ押すだけで残ります。',
  very_easy: 'そういう日があったことも、残しておくと役に立ちます。',
  easy: '記録しました。楽な日の記録も、あとで効いてきます。',
  usual: '記録しました。',
  hard: 'つらい日ですね。記録できたので、今日はここまでで大丈夫です。',
  very_hard: 'しんどい日ですね。無理に書き足さなくて大丈夫です。',
  done: '記録しました。',
};

export function gutLine(mood, { recordedToday } = {}) {
  if (!recordedToday) return GUT_LINES.none;
  return GUT_LINES[mood] || GUT_LINES.done;
}
