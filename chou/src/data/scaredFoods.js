// 「週に一回以上は死んでも食うな」「猛毒食品」「食べたら最後、寝たきり一直線」
// 「99パーセントの医者が毎日食べている神食品」。
//
// **薬を「猛毒」と呼ばないと決めたのと同じ線を、食べものにも引く**（README 決まり26）。
// 理由は3つ。
//  ① **食べものを怖がらせる言い方は、食べられなくする。** このアプリを使う人はお腹の調子で
//     困っている人で、食べるのがこわくなっている人もいる。「一口で認知症2倍」と言われると、
//     合っていたものまで食べられなくなる。
//  ② **高齢者にとって、最大のリスクは食べすぎではなく低栄養。** 出典自身が「衰弱」を
//     3位に挙げているのに、そのすぐ横で「食うな」と言っている。カップラーメンでも
//     食べられるほうがよい人がいる。
//  ③ **1つの食品で1つの病気が決まるわけではない。** 「これを食べたから寝たきりになった」
//     という読み方は、原因をひとつに決めつけるやり方で、当たらない。
//
// **食べものの一覧を「食べるな」の形で持たない。** 持つのは
// 「そう名指しされている」ことと、「気になるなら、どこを見て選ぶか」まで。

