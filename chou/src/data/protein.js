//
// この題材で気をつけたことは4つ。
//  ① **「理想的なバランス」を持たない。** 出典は動物性:植物性＝1:1、水溶性:不溶性＝1:2を
//     「理想」と書くが、手元に無い基準をアプリが持つと、外れた人が「間違っている」ことになる
//     （README 決まり4）。出典の目安として引用はするが、**アプリは計算も採点もしない。**
//  ② **除去（やめてみる）を煽らない。** 小麦・乳製品を断つ話は、食事を強く制限する方向へ
//     押しやすい。**やめてみるのは試すためで、続けるためではない**と必ず書き、
//     摂食障害の経験・成長期・妊娠授乳・腎臓の持病がある人には先に相談を出し続ける。
//  ③ **サプリの量を決めない。** ビタミンDは取りすぎると害が出る栄養素なので、
//     アプリは目安量も飲み方も出さない。
//  ④ **「腸漏れ」は既存の訂正と同じ扱い**（リーキーガット症候群は確立した病名ではない）。
//     出典はこれを前提に話を組み立てているので、前提のほうに印を付ける。

