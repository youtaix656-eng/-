// 科目ごとの決まった読み上げ順（型）。固定順で毎回読む意識を持つと、聞きながら
// 「次は〜が来る」と予測でき記憶が整理しやすい、という考え方（ユーザー提供の音声学習ガイドより）。
// アプリが自動で問題文を「起始／停止／支配神経」等に分解する機能ではない——フリーテキストの
// 解説文を機械的に分解すると誤った切り分けをしかねないため、型そのものを一言案内するだけに留める
// （手元に無い基準で断定しない方針と同じ）。

export const SUBJECT_READING_ORDER = {
  解剖学: '起始→停止→支配神経→作用',
  生理学: '何が→どこで→どうなる→結果どうなる',
  経絡経穴概論: '経絡名→部位→要穴の種類',
  関係法規: '誰が・何を・してはいけない／しなければならないか',
  衛生学公衆衛生学: '数値の境目（以上・未満）を正確に',
  臨床医学総論: '原因→症状→検査→治療',
  臨床医学各論: '原因→症状→検査→治療',
  リハビリテーション医学: '名前→何を評価するか→段階の数',
};

export function readingOrderHintFor(subject) {
  const order = SUBJECT_READING_ORDER[subject];
  if (!order) return null;
  return `「${subject}」は、${order}の順で確認する意識を持ちましょう。`;
}
