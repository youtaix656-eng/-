const idOf = (title) => 'gt-toyo-' + Array.from(title).map((c) => c.codePointAt(0).toString(36)).join('-');

// 用語集（glossaryTerms.js）と同じ形の項目にする
export function buildToyoGlossaryTerms(rows = TOYO_GLOSSARY_ROWS) {
  const titles = new Set(rows.map((r) => r[0]));
  return rows.map(([title, reading, description, related, review]) => {
    const aliases = [];
    const destinations = [];
    for (const part of String(related || '').split('、').map((s) => s.trim()).filter(Boolean)) {
      const [name, aliasReading] = part.split(':');
      if (titles.has(name)) destinations.push({ type: 'system', target: idOf(name), label: `同じ意味の「${name}」を見る` });
      else if (aliasReading) aliases.push({ title: name, reading: aliasReading });
    }
    destinations.push({ type: 'page', target: 'audio', label: '音声学習の画面を開く' });
    return {
      id: idOf(title),
      title,
      reading,
      category: 'toyo',
      description,
      descriptionStatus: review ? 'needs_review' : 'verified',
      aliases,
      destinations,
    };
  });
}

// 音声学習の読み（2文字以上の言葉だけ。1文字の「水」「神」などは文章中の全部に当たるので使わない）
export function toyoSpeechReadings(rows = TOYO_GLOSSARY_ROWS) {
  const out = {};
  for (const [title, reading, , related] of rows) {
    if (title.length >= 2) out[title] = reading;
    for (const part of String(related || '').split('、')) {
      const [name, r] = part.split(':');
      if (r && name && name.trim().length >= 2) out[name.trim()] = r.trim();
    }
  }
  return out;
}
