// 毎年・数年ごとに変わりやすい数値（要更新）だけを抽出
export function volatileNumberFacts() {
  return NUMBER_FACTS.filter((n) => n.volatile);
}

// ユーザーが上書き保存した値（overrides: { [id]: { value, asOf, note, updatedAt } }）を
// 反映した「実効の数値ファクト」を返す。全科目で一括更新できる単一の窓口。
export function effectiveNumberFacts(overrides = {}) {
  return NUMBER_FACTS.map((n) => {
    const o = overrides[n.id];
    if (!o) return n;
    return {
      ...n,
      value: o.value != null && o.value !== '' ? o.value : n.value,
      asOf: o.asOf != null && o.asOf !== '' ? o.asOf : n.asOf,
      note: o.note != null && o.note !== '' ? o.note : n.note,
      updatedAt: o.updatedAt || null,
      edited: true,
    };
  });
}

// キーワードに関係する比較グループ
export function comparisonsForKeyword(kw) {
  return COMPARISONS.filter((c) => c.terms.includes(kw) || c.title.includes(kw));
}
// キーワードに関係する数値ファクト（overrides があれば実効値で返す）
export function numbersForKeyword(kw, overrides) {
  const list = overrides ? effectiveNumberFacts(overrides) : NUMBER_FACTS;
  return list.filter((n) => n.terms.includes(kw) || n.topic.includes(kw));
}

// マインドマップのセンターとして「おすすめ」できるトピック（データが無くても学べる）
export function suggestedCenters() {
  const set = new Set();
  COMPARISONS.forEach((c) => c.terms.slice(0, 2).forEach((t) => set.add(t)));
  NUMBER_FACTS.forEach((n) => n.terms.slice(0, 1).forEach((t) => set.add(t)));
  return [...set];
}
