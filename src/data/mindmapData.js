// マインドマップのセンターとして「おすすめ」できるトピック（データが無くても学べる）
export function suggestedCenters() {
  const set = new Set();
  COMPARISONS.forEach((c) => c.terms.slice(0, 2).forEach((t) => set.add(t)));
  NUMBER_FACTS.forEach((n) => n.terms.slice(0, 1).forEach((t) => set.add(t)));
  return [...set];
}
