/** 語 → その語で引ける言い換えの一覧（search.js が使う） */
export const SYNONYM_INDEX = (() => {
  const map = new Map();
  const add = (key, value) => {
    const list = map.get(key) || new Set();
    list.add(value);
    map.set(key, list);
  };
  for (const [canonical, others] of SYNONYMS) {
    for (const other of others) {
      add(canonical, other);
      add(other, canonical);
      for (const sibling of others) if (sibling !== other) add(other, sibling);
    }
  }
  return map;
})();

