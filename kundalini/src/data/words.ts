// 衝動が来たときに出す短い言葉。
//
// ⚠ 実在の人物の名言を引かない（出典を確かめられないまま人の名前を付けると、
//    もっともらしい嘘になる）。ここにあるのは**このアプリの言葉**で、
//    「◯◯氏の言葉」として画面に出さない。
// ⚠ 責めない・脅さない：「負けたら終わり」「意志が弱い」は置かない。

export const WORDS: string[] = [
  '波は上がって、下がる。いま上がっているだけで、下がるところまでは必ず行く。',
  '決めるのは今じゃなくていい。あと10分だけ、決めるのを後ろへ置く。',
  '立ち上がって、水を飲む。それだけで場面が変わる。',
  '同じ部屋にいると同じことが起きる。まず部屋を出る。',
  'いま体は何を求めている？眠い・疲れた・さみしい、のどれかかもしれない。',
  '戻ってしまっても、記録は消えない。ここまで見てきたことは残る。',
  '数えるのは道具。あなたの価値とは関係がない。',
  '呼吸を4つ数えて吸って、8つ数えて吐く。それを3回だけ。',
  '10分後の自分に決めさせる。いまの自分は疲れている。',
  'この気持ちは消さなくていい。ただ、いま何もしなくていい。',
];

/** 日付や時刻から決める（乱数を使わない＝同じ瞬間なら同じ言葉が出る） */
export function wordAt(at: number): string {
  const i = Math.floor(at / 60000) % WORDS.length;
  return WORDS[i];
}
