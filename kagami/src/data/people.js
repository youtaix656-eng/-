/** ふるまいの全一覧（画面のチェック項目。型ごとの id を付けて返す） */
export function allBehaviors() {
  const out = [];
  for (const t of PERSON_TYPES) {
    t.behaviors.forEach((text, i) => {
      out.push({ id: `${t.id}:${i}`, typeId: t.id, text });
    });
  }
  return out;
}
