// 心理的な操作の「型」カタログ — このアプリの単一の正。
//
// 画面にも判定にも if を足さない。型を1件足せば、一覧・目次・貼って調べる・
// 自分の言い方を見る、のすべてが自動で追従する。
//
// 守ること:
//   1. **点数・危険度・順位を付けない。** 「危険度80点」を出すには他人の事例という
//      手元に無い基準が要る。出せるのは「どの型の言い回しに当たったか」だけ。
//   2. **当たった＝操作されている、ではない。** 同じ言葉は普通の会話でも使う。
//      cues は言葉が一致しただけの手がかりで、判断するのは読んだ人。
//   3. **効き目の大きさを書かない**（「◯％の人が従う」は実験の条件次第で変わる）。
//   4. 出典（sourceIds）を必ず持つ。返し方（replyIds）も必ず1つ以上持つ。
//   5. 漢字を含む name には reading（ひらがな）を必ず書く。自動推定はしない。
//   6. cues は**その型に特徴的な言い回し**だけ。「ありがとう」のような
//      どこにでも出る語を入れると、何を貼っても全部の型が当たって役に立たなくなる。

