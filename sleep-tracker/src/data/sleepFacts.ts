export function pickFactOfTheDay(dateSeed = new Date()): SleepFact {
  const dayIndex = Math.floor(dateSeed.getTime() / (24 * 60 * 60 * 1000));
  const idx = ((dayIndex % SLEEP_FACTS.length) + SLEEP_FACTS.length) % SLEEP_FACTS.length;
  return SLEEP_FACTS[idx];
}
