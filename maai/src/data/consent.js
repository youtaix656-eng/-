//      言わせ方・断らせない言い方は、このアプリのどこにも置かない。
//   2. **法律の条文を数字で断定しない。** 年齢・罪名・要件は改正で変わる。
//      公式（法務省・警察・自治体の窓口）で確かめる、と書く。※要確認を付ける。
//   3. **性別で書かない。** 誘う側・誘われる側のどちらにも同じ条件が掛かる。
//   4. **点数を付けない・診断しない。**

