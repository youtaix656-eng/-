//
// **これは使い方の説明ではなく、気づくための一覧。**
// 画面にも判定にも if を足さない。1件足せば、一覧・目次・貼って調べる・
// 自分の書いた文面を見る、のすべてが自動で追従する。
//
// 守ること（tactics.test.mjs が機械チェックする）:
//   1. **点数・危険度・順位を付けない。** 「危険度80点」を出すには他人の事例という
//      手元に無い基準が要る。出せるのは「どの型の言い回しに当たったか」だけ。
//   2. **当たった＝相手が悪い、ではない。** 同じ言葉はふつうの恋愛でも使う。
//      cues は言葉が一致しただけの手がかりで、判断するのは読んだ人。
//   3. **手順として書かない。** 書くのは「どう見えるか（signs）」と
//      「なぜ効いてしまうか（why）」。うまくやる方法・断らせないコツは書かない。
//   4. **効き目の大きさを書かない**（「◯％が落ちる」は実験の条件次第で変わる）。
//   5. 出典（sourceIds）と、できること（replyIds）を必ず持つ。
//   6. 漢字を含む name には reading（ひらがな）を必ず書く。自動推定しない。
//   7. cues は**その型に特徴的な言い回し**だけ。「好き」のようにどこにでも出る語を
//      入れると、何を貼っても全部の型が当たって役に立たなくなる。
//   8. 言葉に残らない型（channel:'behavior'）は cues も lines も持たない。
//      **読めないものを読めるふりをしない**——文面からは絶対に当てない。

