// 近づき方の型 — 「自分の側でできること」だけを集めたカタログ。
//
// このアプリの半分はここで、もう半分は tactics.js（人を思いどおりにする型）。
// 層が違うので**混ぜない**：こちらは自分が動かすもの、あちらは相手が動かしてくるもの。
//
// 守ること（approach.test.mjs が機械チェックする）:
//   1. **相手の同意が要ることを「手順」として書かない。** how に書けるのは
//      自分の側だけで完結すること（行く・聞く・待つ・引く・言う）だけ。
//      酔わせる・退路を断つ・押し切る・既成事実にする——これらは手順ではなく
//      tactics.js の「型」として、される側が気づくために置く。
//   2. **効き目の大きさを書かない。** 「◯％の人が」「必ず落ちる」「誰でも」は書かない。
//      同じ手が効くかどうかは相手と場面で変わるので、断定した時点で嘘になる。
//   3. **確からしさを正直に書く**（evidence）。よく確かめられているもの・結果が割れて
//      いるもの・言われているだけのものを混ぜない。thin（言われているだけ）を
//      「研究によると」と書かない。
//   4. 出典（sourceIds）を必ず持つ。**URL は持たない**（sources.js を見よ）。
//   5. 漢字を含む name には reading（ひらがな）を必ず書く。自動推定しない。

